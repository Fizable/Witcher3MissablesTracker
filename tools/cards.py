def clean_label(value):
    text = re.sub(r"^_*(?:EP2_)?store__", "", value or "")
    text = text.replace("_", " ").strip()
    return re.sub(r"\s+", " ", text)


def locid_map(titles):
    """{title key: STRING_ID} for the card display names, from the game's string database."""
    wanted = {title.strip() for title in titles if title and title.strip()}
    if not wanted:
        return {}
    conn = stringsdb.con()
    out = {}
    try:
        keys = sorted(wanted)
        for i in range(0, len(keys), 300):
            chunk = keys[i:i + 300]
            q = ("select STRING_KEY, STRING_ID from STRING_INFO where STRING_KEY in (%s)"
                 % ",".join("?" * len(chunk)))
            for key, sid in conn.execute(q, chunk):
                if key is not None:
                    out[str(key).strip()] = sid
    finally:
        conn.close()
    return out


def phase_steps():
    """{normalized phase path: route step} where the index names exactly one owning quest."""
    index_path = HERE / "quest_index.json"
    if not index_path.exists():
        return {}
    doc = load_json(index_path)
    claims = collections.defaultdict(set)
    for stem, quest in (doc.get("quests") or {}).items():
        if not isinstance(quest, dict):
            continue
        names = quest.get("bundle_names") or [stem]
        step = names[0] if isinstance(names, list) and names else stem
        for phase in quest.get("phases") or []:
            path = phase.get("file") if isinstance(phase, dict) else phase
            if isinstance(path, str) and path:
                claims[norm(path)].add(step)
    return {path: next(iter(steps)) if len(steps) == 1 else "" for path, steps in claims.items()}


def leader_items(leaders, items):
    """Same item identity rule the probe uses for leader cards."""
    by_name = {item["name"] for item in items}
    for leader in leaders:
        exact = "gwint_card_" + leader["name"]
        leader["items"] = [exact] if exact in by_name else []
        if leader["name"] == "king_bran" and "gwint_card_king_bran_bronze" in by_name:
            leader["items"] = ["gwint_card_king_bran_bronze"]
    return leaders


def script_path(relative):
    """(game-relative virtual path, pack) for a native script.

    The data never carries an absolute install path. The base script tree is preferred, then the
    DLC script trees, then the REDkit mirror when the game install has no script folder.
    """
    relative = relative.replace("\\", "/")
    base = probe.GAME / "content" / "content0" / "scripts"
    if (base / relative).exists():
        return "content/content0/scripts/" + relative, "base"
    for root in sorted((probe.GAME / "DLC").glob("*/content/scripts")):
        if not (root / relative).exists():
            continue
        pack = root.parent.parent.name
        return "dlc/%s/content/scripts/%s" % (pack, relative), pack
    redkit = probe.REDKIT_R4 / "scripts"
    if (redkit / relative).exists():
        return "r4data/scripts/" + relative, "base"
    return "content/content0/scripts/" + relative, "base"


def script_pack(path, function):
    if function == "UnlockSkelligeGwentDeck":
        return "bob"  # invoked from the Blood and Wine tournament quest
    parts = path.replace("\\", "/").lower().split("/")
    if len(parts) > 3 and parts[0] == "dlc":
        return parts[1]
    return "base"


def deck_index_map(cards):
    name_to_cards = collections.defaultdict(set)
    for card in cards:
        for key in (card["name"], card["title"], card["display"]):
            if key:
                name_to_cards[key.lower()].add(card["index"])
        for item in card["items"]:
            name_to_cards[item.lower()].add(card["index"])
            name_to_cards[item.replace("gwint_card_", "").lower()].add(card["index"])
    return name_to_cards


def deck_cards(deck, name_to_cards):
    out = set()
    for name in deck["cards"]:
        base = name[11:] if name.lower().startswith("gwint_card_") else name
        for key in (name.lower(), base.lower(), ("gwint_card_" + base).lower()):
            out.update(name_to_cards.get(key, set()))
    return out


def source_row(kind, text, **fields):
    row = {"kind": kind, "text": text}
    for key, value in fields.items():
        if value not in (None, "", [], {}):
            row[key] = value
    row["confidence"] = "weak" if kind in ("opponent_deck", "deck_definition") else (
        "unknown" if kind == "unknown" else "strong")
    return row


def card_refs(name, cards_by_name, card_items, leaders_by_name, leader_items_by_index):
    """(collection, index) pairs for a script name or gwint_card_* item."""
    base = name[11:] if name.lower().startswith("gwint_card_") else name
    out = set()
    for key in (name, base, "gwint_card_" + base):
        card = cards_by_name.get(key)
        if card:
            out.add(("main", card["index"]))
        leader = leaders_by_name.get(key)
        if leader:
            out.add(("leader", leader["index"]))
        for index in card_items.get(key, ()):
            out.add(("main", index))
        for index in leader_items_by_index.get(key, ()):
            out.add(("leader", index))
    return out


def build_doc():
    if not probe.GAME.is_dir():
        raise SystemExit(f"game folder not found: {probe.GAME}")
    bundles = probe.Bundles()
    if not bundles.by_path:
        raise SystemExit("no readable game bundles under content/ or DLC/")
    card_hit = bundles.choose(CARD_FILE)
    item_hit = bundles.choose(ITEM_FILE)
    leader_hit = bundles.choose(LEADER_FILE)
    king_hit = bundles.choose(probe.KING_DB)
    deck_hit = bundles.choose(DECK_FILE)
    missing = [path for path, hit in ((CARD_FILE, card_hit), (ITEM_FILE, item_hit),
                                      (LEADER_FILE, leader_hit), (probe.KING_DB, king_hit),
                                      (DECK_FILE, deck_hit))
               if not hit]
    if missing:
        raise SystemExit("missing card resources in the game bundles: " + ", ".join(missing))

    cards = probe.read_cards(probe.xml_root(card_hit[2]))
    leaders = probe.read_cards(probe.xml_root(leader_hit[2]))
    items = probe.read_items(probe.xml_root(item_hit[2]))
    king_count = len(probe.xml_root(king_hit[2]).findall(".//card"))
    conn = probe.resolve_names(cards, leaders)
    try:
        pass
    finally:
        conn.close()
    probe.link_items(cards, items)
    leader_items(leaders, items)

    cards_by_index = {card["index"]: card for card in cards}
    leaders_by_index = {leader["index"]: leader for leader in leaders}
    cards_by_name = {card["name"]: card for card in cards}
    leaders_by_name = {leader["name"]: leader for leader in leaders}
    card_items = collections.defaultdict(set)
    for card in cards:
        for item in card["items"]:
            card_items[item].add(card["index"])
    leader_items_by_index = collections.defaultdict(set)
    for leader in leaders:
        for item in leader["items"]:
            leader_items_by_index[item].add(leader["index"])

    summons = probe.summon_only_cards(cards)
    summon_ids = {row["index"] for row in summons}
    rows = collections.defaultdict(list)
    seen_rows = collections.defaultdict(set)
    route_ids = set()
    route_path = TRACKER / "data" / "route.json"
    if route_path.exists():
        route_ids = {node.get("id") for node in load_json(route_path).get("nodes", [])
                     if isinstance(node, dict)}
    steps = {path: step for path, step in phase_steps().items()
             if not step or step in route_ids}

    def add(collection, index, row):
        signature = json.dumps(row, sort_keys=True)
        if signature not in seen_rows[(collection, index)]:
            seen_rows[(collection, index)].add(signature)
            rows[(collection, index)].append(row)

    # ---- XML sources: vendor shops, quest loot, unique loot, rewards
    for kind, virtual_path in probe.SOURCE_FILES:
        hit = bundles.choose(virtual_path)
        if not hit:
            continue
        text = probe.decode_payload(hit[2])
        source_rows = (probe.read_reward_rows(text, virtual_path) if kind == "reward"
                       else probe.read_loot_rows(text, kind, virtual_path))
        for row in source_rows:
            for collection, index in card_refs(row["item"], cards_by_name, card_items,
                                               leaders_by_name, leader_items_by_index):
                if kind == "vendor":
                    label = clean_label(row["container"])
                    text = f"Sold by {label}"
                elif kind == "quest":
                    text = f"Quest loot: {clean_label(row['container'])}"
                elif kind == "unique":
                    text = f"Unique loot: {clean_label(row['container'])}"
                else:
                    text = f"Quest reward event: {clean_label(row['container'])}"
                add(collection, index, source_row(
                    kind, text, container=row["container"], file=virtual_path, pack=row["pack"]))

    # ---- phase grants: exact script grant rows, attributed to the phase's quest step
    phase = probe.scan_phase_grants(bundles)
    for row in phase["grants"]:
        step = steps.get(norm(row["file"]), "")
        target = "merchant_card" if row["kind"] == "merchant_card" else "phase_grant"
        if target == "merchant_card":
            text = ("Merchant card grant in %s (%s)"
                    % (Path(row["file"].replace("\\", "/")).stem, row["function"]))
        else:
            text = ("Scripted quest grant in %s (%s)"
                    % (Path(row["file"].replace("\\", "/")).stem, row["function"]))
        for collection, index in card_refs(row["item"], cards_by_name, card_items,
                                           leaders_by_name, leader_items_by_index):
            add(collection, index, source_row(
                target, text, file=row["file"], step=step, pack=row["pack"],
                function=row["function"]))

    # ---- native script grants and the random merchant pool
    native = probe.scan_native_scripts()
    for row in native["grants"]:
        path, _root_pack = script_path(row["file"])
        pack = script_pack(path, row["function"])
        text = ("Collection grant by %s() in %s:%s"
                % (row["function"], Path(path).name, row["line"]))
        # A native collection grant is the one source that outranks a phase grant: the card is in
        # the collection from the moment the game sets the deck up, not only from a quest phase.
        kind = ("collection_grant" if row["function"] in
                ("OnGwintSetupNewgame", "UnlockSkelligeGwentDeck") else "native_script")
        for name in row["names"]:
            for collection, index in card_refs(name, cards_by_name, card_items,
                                               leaders_by_name, leader_items_by_index):
                add(collection, index, source_row(
                    kind, text, file=path, function=row["function"],
                    line=row["line"], pack=pack))
    for row in native["random_pools"]:
        path, _root_pack = script_path(row["file"])
        text = ("Random merchant card reward (%s in %s:%s; the specific merchant is not identified)"
                % (row["function"], Path(path).name, row["line"]))
        for item in row["items"]:
            for collection, index in card_refs(item, cards_by_name, card_items,
                                               leaders_by_name, leader_items_by_index):
                add(collection, index, source_row(
                    "random_merchant", text, file=path, function=row["function"],
                    line=row["line"], pack=script_pack(path, row["function"])))

    # ---- deck evidence: the starter deck is a grant; named decks are opponent evidence only
    decks, _total_decks, _total_lines = probe.read_decks(probe.decode_payload(deck_hit[2]))
    mapping = deck_index_map(cards)
    starter = set()
    opponent = collections.defaultdict(set)
    for deck in decks:
        indices = deck_cards(deck, mapping)
        if deck["kind"] == "player" and deck["name"].lower() == "north":
            starter.update(indices)
        elif deck["kind"] == "named":
            for index in indices:
                opponent[index].add(deck["name"])
    for index in sorted(starter):
        add("main", index, source_row(
            "deck_definition",
            "Northern Kingdoms deck definition; a deck list is not a collection grant",
            file=DECK_FILE, pack="base"))
    for index, names in sorted(opponent.items()):
        label = ", ".join(sorted(names))
        add("main", index, source_row(
            "opponent_deck",
            f"Appears in the {label} opponent deck; opponent evidence, not a proven reward",
            file=DECK_FILE, pack="base", container=label))

    # ---- reviewed leader evidence (the probe's section 3.1 decisions)
    default_leaders = {
        "foltest_copper": "Northern Kingdoms",
        "emhyr_copper": "Nilfgaard",
        "francesca_copper": "Scoia'tael",
    }
    for name, faction in default_leaders.items():
        leader = leaders_by_name.get(name)
        if leader:
            add("leader", leader["index"], source_row(
                "deck_default", f"Default {faction} deck leader", file=DECK_FILE, pack="base"))
    crach = leaders_by_name.get("Crach_an_Craite")
    if crach:
        path, _root_pack = script_path("game/gui/menus/gwintManager.ws")
        add("leader", crach["index"], source_row(
            "native_script",
            "Fixed Skellige deck leader assigned by OnGwintSetupSkellige()",
            file=path, function="OnGwintSetupSkellige", pack="bob"))
    eredin = leaders_by_name.get("eredin_copper")
    if eredin:
        add("leader", eredin["index"], source_row(
            "unknown", "unknown source", file=LEADER_FILE, pack="base"))

    titles = [card.get("title", "") for card in cards + leaders]
    title_locids = locid_map(titles)

    def card_pack(collection, index):
        # The card table is the base table: ep1/bob shops sell base cards, so a DLC source row
        # does not make the definition a DLC card. Skellige itself is the Blood and Wine deck:
        # its cards are the 500-527 block plus `mushroom` (Mardroeme), which reuses index 22 but
        # is granted by UnlockSkelligeGwentDeck(). Faction is the authoritative marker; two
        # Skellige leaders are the only leaders outside the base factions.
        source_row = leaders_by_index[index] if collection == "leader" else cards_by_index[index]
        return "bob" if source_row["faction"] == "F_SKELLIGE" else "base"

    def evidence(collection, index, row_list):
        source = leaders_by_index[index] if collection == "leader" else cards_by_index[index]
        out = []
        for row in row_list:
            if row.get("file"):
                out.append({"kind": "file", "value": row["file"]})
        title = (source.get("title") or "").strip()
        if title:
            out.append({"kind": "string_key", "value": title})
        locid = title_locids.get(title)
        if locid:
            out.append({"kind": "locid", "value": locid})
        if not out:
            out.append({"kind": "file", "value": CARD_FILE if collection == "main" else LEADER_FILE})
        seen, unique = set(), []
        for row in sorted(out, key=lambda r: (r["kind"], str(r["value"]))):
            key = (row["kind"], row["value"])
            if key not in seen:
                seen.add(key)
                unique.append(row)
        return unique

    shipped = []
    for collection, source in (("main", cards), ("leader", leaders)):
        for card in sorted(source, key=lambda c: c["index"]):
            if collection == "main" and card["index"] in summon_ids:
                continue
            row_list = rows.get((collection, card["index"]), [])
            row_list = sorted(row_list, key=lambda r: (SOURCE_PRIORITY.get(r["kind"], 99),
                                                       str(r.get("file", "")),
                                                       str(r.get("container", "")),
                                                       str(r.get("text", ""))))
            if not row_list:
                row_list = [source_row("unknown", "unknown source",
                                       file=CARD_FILE if collection == "main" else LEADER_FILE,
                                       pack=card_pack(collection, card["index"]))]
            # Opponent-deck membership says where a card is played, not that the player can win
            # it there. A card with only that evidence has no proven source, so the primary row is
            # the explicit unknown source and the opponent row stays as weak evidence.
            if not any(row["confidence"] == "strong" for row in row_list):
                unknown_row = source_row("unknown", "unknown source",
                                         file=CARD_FILE if collection == "main" else LEADER_FILE,
                                         pack=card_pack(collection, card["index"]),
                                         container="no concrete grant or vendor row")
                if not any(row["kind"] == "unknown" for row in row_list):
                    row_list = [unknown_row] + row_list
            primary = row_list[0]
            item = {
                "id": ("card_" if collection == "main" else "leader_") + card["name"].lower(),
                "index": card["index"],
                "collection": collection,
                "name": card["display"],
                "internal_name": card["name"],
                "deck": DECK_NAMES.get(card["faction"], card["faction"]),
                "faction": card["faction"],
                "pack": card_pack(collection, card["index"]),
                "source": primary,
                "sources": row_list,
                "evidence": evidence(collection, card["index"], row_list),
            }
            title = (card.get("title") or "").strip()
            if title:
                item["name_key"] = title
            locid = title_locids.get(title)
            if locid:
                item["name_locid"] = locid
            if collection == "leader" and card["name"] == "Crach_an_Craite":
                item["ownership"] = "deck_default"
                item["ownership_note"] = (
                    "A fixed deck leader, not a normal SBLeaderCollectionCard row; the save "
                    "collection or the Skellige deck-unlock fact decides it, otherwise unknown."
                )
            shipped.append(item)

    excluded = []
    for row in summons:
        parent = row["parents"][0] if row["parents"] else {}
        parent_card = cards_by_index.get(parent.get("index"))
        parent_label = (parent_card or {}).get("display") or parent.get("name", "another card")
        note = (f"Summoned by {parent_label} "
                f"through {'/'.join(row['effects']) or 'a summon effect'}; a token, not a "
                "collectible card.")
        if row["name"] == "hemdal":
            note += " Its item is also marked UNOBTAINABLE IN GAME."
        excluded.append({
            "id": "card_" + row["name"].lower(),
            "index": row["index"],
            "collection": "main",
            "name": row["display"],
            "internal_name": row["name"],
            "reason": "summon_only",
            "note": note,
            "evidence": [
                {"kind": "card_xml", "value": CARD_FILE},
                {"kind": "item_xml", "value": ITEM_FILE},
                {"kind": "summon_flag",
                 "value": f"{parent_label} -> {row['display']} ({'/'.join(row['effects'])})"},
            ],
        })

    by_pack = collections.Counter(card["pack"] for card in shipped)
    known = sum(1 for card in shipped if card["source"]["kind"] != "unknown")
    unknown = len(shipped) - known
    doc = {
        "version": 1,
        "note": ("Generated by tools/cards.py from the game's card XML, scripts and string "
                 "database. Do not hand-edit. The denominator is collectible definitions: "
                 "main cards plus leaders; summon-only tokens are listed in excluded."),
        "denominator": len(shipped),
        "counts": {
            "main_definitions": len(cards),
            "main_collectible": len(cards) - len(summons),
            "leaders": len(leaders),
            "king_cards_active": king_count,
            "total_definitions": len(cards) + len(leaders),
            "excluded_summon_only": len(summons),
            "total": len(shipped),
            "with_source": known,
            "unknown_source": unknown,
            "missable": 0,
            "packs": {pack: by_pack.get(pack, 0) for pack in PACKS},
        },
        "missable_windows": {
            "proven": False,
            "note": "Card windows are attached after the source rows are built.",
        },
        "excluded": sorted(excluded, key=lambda row: row["index"]),
        "cards": shipped,
    }
    return cardwindows.attach(doc)


def validate_schema(doc, errors):
    def err(path, message):
        errors.append(f"{path}: {message}")

    if not isinstance(doc, dict):
        err("file", "must be a JSON object")
        return
    for key in sorted(set(doc) - {"version", "note", "denominator", "counts", "missable_windows",
                                  "excluded", "cards"}):
        err(str(key), "unknown top-level key")
    if doc.get("version") != 1:
        err("version", "must be 1")
    if not isinstance(doc.get("note"), str) or not doc["note"]:
        err("note", "must be a non-empty string")
    cards = doc.get("cards")
    excluded = doc.get("excluded")
    if not isinstance(cards, list):
        err("cards", "must be a list")
        cards = []
    if not isinstance(excluded, list):
        err("excluded", "must be a list")
        excluded = []
    if not isinstance(doc.get("denominator"), int) or doc.get("denominator") != len(cards):
        err("denominator", "must equal the number of cards")
    counts = doc.get("counts")
    if not isinstance(counts, dict):
        err("counts", "must be an object")
        counts = {}
    for key in ("main_definitions", "main_collectible", "leaders", "king_cards_active",
                "total_definitions", "excluded_summon_only", "total", "with_source",
                "unknown_source", "missable"):
        if not isinstance(counts.get(key), int):
            err(f"counts.{key}", "must be an integer")
    packs = counts.get("packs")
    if not isinstance(packs, dict) or set(packs) != set(PACKS):
        err("counts.packs", f"must have exactly {', '.join(PACKS)}")
    windows = doc.get("missable_windows")
    if not isinstance(windows, dict) or not isinstance(windows.get("proven"), bool):
        err("missable_windows", "must be an object with a boolean proven")
    elif windows.get("proven") is not False:
        err("missable_windows.proven", "must be false: the shipped missable rows are Tier B")
    if not isinstance(windows, dict) or windows.get("reviewed") is not True:
        err("missable_windows.reviewed", "must be true once every card has a window")
    for key in ("tier_a", "tier_b", "tier_c", "missable", "one_time", "none"):
        if not isinstance((windows or {}).get(key), int):
            err("missable_windows." + key, "must be an integer")

    ids, indices = set(), set()
    for i, card in enumerate(cards):
        path = f"cards[{i}]"
        if not isinstance(card, dict):
            err(path, "must be an object")
            continue
        for key in sorted(set(card) - {"id", "index", "collection", "name", "internal_name",
                                       "deck", "faction", "pack", "source", "sources", "evidence",
                                       "name_key", "name_locid", "ownership", "ownership_note",
                                       "missable", "window"}):
            err(path, f"unknown key {key!r}")
        for key in ("id", "name", "internal_name", "deck", "faction", "pack"):
            if not isinstance(card.get(key), str) or not card[key].strip():
                err(path + "." + key, "must be a non-empty string")
        cid = card.get("id")
        if not isinstance(cid, str) or not ID.fullmatch(cid):
            err(path + ".id", "must match ^[a-z][a-z0-9_]{2,63}$")
        elif cid in ids:
            err(path + ".id", f"duplicate card id {cid!r}")
        else:
            ids.add(cid)
        index = card.get("index")
        if not isinstance(index, int) or isinstance(index, bool) or index < 0:
            err(path + ".index", "must be a non-negative integer")
        elif (card.get("collection"), index) in indices:
            err(path + ".index", f"duplicate index {index!r}")
        else:
            indices.add((card.get("collection"), index))
        if card.get("collection") not in ("main", "leader"):
            err(path + ".collection", "must be 'main' or 'leader'")
        if card.get("pack") not in PACKS:
            err(path + ".pack", f"must be one of {', '.join(PACKS)}")
        if "name_locid" in card and (not isinstance(card["name_locid"], int)
                                     or card["name_locid"] <= 0):
            err(path + ".name_locid", "must be a positive integer")
        if "ownership" in card and card["ownership"] != "deck_default":
            err(path + ".ownership", "only 'deck_default' is supported")
        for key in ("name", "deck", "ownership_note"):
            value = card.get(key)
            if isinstance(value, str):
                for token in PLACEHOLDERS:
                    if token in value:
                        err(path + "." + key, f"contains placeholder token {token!r}")
        sources = card.get("sources")
        if not isinstance(sources, list) or not sources:
            err(path + ".sources", "must be a non-empty list")
            sources = []
        source = card.get("source")
        if not isinstance(source, dict):
            err(path + ".source", "must be an object")
        seen_sources = set()
        for j, row in enumerate(sources):
            sp = f"{path}.sources[{j}]"
            if not isinstance(row, dict):
                err(sp, "must be an object")
                continue
            kind = row.get("kind")
            if kind not in SOURCE_KINDS:
                err(sp + ".kind", f"must be one of {', '.join(SOURCE_KINDS)}")
            if not isinstance(row.get("text"), str) or not row["text"].strip():
                err(sp + ".text", "must be a non-empty string")
            for token in PLACEHOLDERS:
                if isinstance(row.get("text"), str) and token in row["text"]:
                    err(sp + ".text", f"contains placeholder token {token!r}")
            if row.get("confidence") not in ("strong", "weak", "unknown"):
                err(sp + ".confidence", "must be strong, weak or unknown")
            if kind == "unknown" and row.get("confidence") != "unknown":
                err(sp + ".confidence", "an unknown source must be marked unknown")
            if kind != "unknown" and row.get("confidence") == "unknown":
                err(sp + ".confidence", "only an unknown source is marked unknown")
            if "step" in row and (not isinstance(row["step"], str) or not row["step"]):
                err(sp + ".step", "must be a non-empty route step id")
            if "locid" in row and (not isinstance(row["locid"], int) or row["locid"] <= 0):
                err(sp + ".locid", "must be a positive integer")
            signature = json.dumps(row, sort_keys=True)
            if signature in seen_sources:
                err(sp, "duplicate source row")
            seen_sources.add(signature)
        if isinstance(source, dict) and source not in sources:
            err(path + ".source", "must be the first row in sources")
        evidence = card.get("evidence")
        if not isinstance(evidence, list) or not evidence:
            err(path + ".evidence", "must be a non-empty list")
        else:
            for j, row in enumerate(evidence):
                if not isinstance(row, dict) or row.get("kind") not in (
                        "file", "locid", "string_key", "card_xml", "item_xml", "summon_flag"):
                    err(f"{path}.evidence[{j}]", "must have a known kind")
                if "value" not in row or row["value"] in (None, ""):
                    err(f"{path}.evidence[{j}].value", "must not be empty")
        window = card.get("window")
        if not isinstance(window, dict):
            err(path + ".window", "must be an object")
        else:
            kind = window.get("kind")
            if kind not in ("missable", "one_time", "none"):
                err(path + ".window.kind", "must be missable, one_time or none")
            if window.get("tier") not in ("gamefile", "community", "unknown"):
                err(path + ".window.tier", "must be gamefile, community or unknown")
            if kind in ("missable", "one_time"):
                for key in ("step", "event", "mechanism"):
                    if not isinstance(window.get(key), str) or not window[key]:
                        err(path + ".window." + key, "must be a non-empty string")
            if kind == "none" and (not isinstance(window.get("reason"), str)
                                   or not window["reason"]):
                err(path + ".window.reason", "a no-window row must say why")
            if kind == "missable" and window.get("tier") == "community":
                source = window.get("source")
                if not isinstance(source, dict):
                    err(path + ".window.source", "a Tier B row needs a source")
                else:
                    for key in ("name", "url", "reviewed"):
                        if not isinstance(source.get(key), str) or not source[key]:
                            err(path + f".window.source.{key}", "must be a non-empty string")
            if not isinstance(window.get("evidence"), list) or not window["evidence"]:
                err(path + ".window.evidence", "must not be empty")

    ex_ids = set()
    for i, row in enumerate(excluded):
        path = f"excluded[{i}]"
        if not isinstance(row, dict):
            err(path, "must be an object")
            continue
        if row.get("id") in ids:
            err(path + ".id", "an excluded definition must not also be a card")
        if row.get("id") in ex_ids:
            err(path + ".id", "duplicate excluded id")
        ex_ids.add(row.get("id"))
        if row.get("reason") != "summon_only":
            err(path + ".reason", "only the reviewed summon_only exclusion is supported")
        if not isinstance(row.get("note"), str) or not row["note"]:
            err(path + ".note", "must say why the definition is excluded")
        if not isinstance(row.get("evidence"), list) or not row["evidence"]:
            err(path + ".evidence", "must not be empty")
    if counts.get("total") != len(cards):
        err("counts.total", "must equal the number of cards")
    if counts.get("excluded_summon_only") != len(excluded):
        err("counts.excluded_summon_only", "must equal the number of excluded definitions")
    if counts.get("unknown_source") != sum(
            1 for card in cards if isinstance(card, dict)
            and isinstance(card.get("source"), dict)
            and card["source"].get("kind") == "unknown"):
        err("counts.unknown_source", "does not match the unknown source rows")


def live_checks(doc, errors, warnings):
    if not probe.GAME.is_dir():
        errors.append(f"game folder not found: {probe.GAME}")
        return
    bundles = probe.Bundles()
    hits = {path: bundles.choose(path) for path in
            (CARD_FILE, ITEM_FILE, LEADER_FILE, probe.KING_DB, DECK_FILE)}
    if any(not hit for hit in hits.values()):
        errors.append("one or more card resources are missing from the game bundles")
        return
    cards = probe.read_cards(probe.xml_root(hits[CARD_FILE][2]))
    leaders = probe.read_cards(probe.xml_root(hits[LEADER_FILE][2]))
    items = probe.read_items(probe.xml_root(hits[ITEM_FILE][2]))
    king_count = len(probe.xml_root(hits[probe.KING_DB][2]).findall(".//card"))
    conn = probe.resolve_names(cards, leaders)
    try:
        pass
    finally:
        conn.close()
    probe.link_items(cards, items)
    leader_items(leaders, items)
    summons = probe.summon_only_cards(cards)
    cards_by_index = {card["index"]: card for card in cards}
    leaders_by_index = {leader["index"]: leader for leader in leaders}
    summon_ids = {row["index"] for row in summons}

    shipped = doc.get("cards") if isinstance(doc.get("cards"), list) else []
    excluded = doc.get("excluded") if isinstance(doc.get("excluded"), list) else []
    route_path = TRACKER / "data" / "route.json"
    route_ids = set()
    if route_path.exists():
        route_ids = {node.get("id") for node in load_json(route_path).get("nodes", [])
                     if isinstance(node, dict)}
    for card in shipped:
        for row in card.get("sources") or []:
            if isinstance(row, dict) and row.get("step") and row["step"] not in route_ids:
                errors.append(f"{card.get('id')}: source step {row['step']!r} is not in route.json")
        window = card.get("window")
        if isinstance(window, dict) and window.get("step") and window["step"] not in route_ids:
            errors.append(f"{card.get('id')}: window step {window['step']!r} is not in route.json")
    by_key = {}
    for card in shipped:
        if isinstance(card, dict):
            by_key[(card.get("collection"), card.get("index"))] = card
    for collection, source, skipped in (("main", cards, summon_ids), ("leader", leaders, set())):
        for card in source:
            if collection == "main" and card["index"] in skipped:
                continue
            row = by_key.get((collection, card["index"]))
            if row is None:
                errors.append(f"missing {collection} card {card['name']!r} (index {card['index']})")
                continue
            if row.get("internal_name") != card["name"]:
                errors.append(f"{row.get('id')}: internal_name does not match the live definition")
            if row.get("name") != card["display"]:
                errors.append(f"{row.get('id')}: name does not match the string database")
    for key in sorted(set(by_key) - {(c, card["index"]) for c in ("main", "leader")
                                     for card in (cards if c == "main" else leaders)}):
        errors.append(f"{key}: card is not in the live definitions")
    if len(by_key) != len(cards) - len(summons) + len(leaders):
        errors.append(f"card count is {len(by_key)}, expected {len(cards) - len(summons) + len(leaders)}")
    counts = doc.get("counts") if isinstance(doc.get("counts"), dict) else {}
    if counts.get("king_cards_active") != king_count:
        errors.append(f"counts.king_cards_active is {counts.get('king_cards_active')!r}, "
                      f"expected {king_count} from the live king-card table")
    if {row.get("internal_name") for row in excluded} != {
            row["name"] for row in summons}:
        errors.append("excluded definitions do not match the live summon-only tokens")
    if any(row.get("index") not in summon_ids for row in excluded):
        errors.append("an excluded definition is not a live summon-only token")

    # name locIds must resolve and equal the shipped name
    strings = stringsdb.con()
    try:
        for row in shipped:
            locid = row.get("name_locid")
            if locid is None:
                continue
            text = stringsdb.loc(locid, strings)
            if not text:
                errors.append(f"{row.get('id')}: name_locid {locid} has no text")
            elif re.sub(r"<br\s*/?>", " / ", text).strip() != row.get("name"):
                errors.append(f"{row.get('id')}: name_locid text does not equal name")
    finally:
        strings.close()


def ownership(doc, save_path, manual=None):
    manual = set(manual or ())
    save = probe.save_collection(Path(save_path)) if save_path else {
        "ok": False, "reason": "no save", "path": "", "name": ""}
    states, reasons = {}, {}
    if save.get("ok"):
        normal = {index: copies for index, copies in save["normal"] if copies > 0}
        leaders = {index: copies for index, copies in save["leaders"] if copies > 0}
        facts = None
        deck_unlocked = False
        for card in doc.get("cards", []):
            cid = card["id"]
            if cid in manual:
                states[cid] = "owned"
                continue
            if card["collection"] == "main":
                states[cid] = "owned" if card["index"] in normal else "not_owned"
                continue
            if card.get("ownership") == "deck_default" and card["index"] not in leaders:
                if facts is None:
                    try:
                        facts = save_reader.facts(save_reader.load_raw(save_path))
                    except Exception as exc:
                        facts = {}
                        reasons[cid] = f"save facts unreadable: {exc}"
                deck_unlocked = bool(facts.get("skel_gwint_base_deck_given"))
                if not deck_unlocked:
                    states[cid] = "unknown"
                    reasons.setdefault(cid, "deck leader with no collection row and no deck-unlock fact")
                else:
                    states[cid] = "owned"
                continue
            states[cid] = "owned" if card["index"] in leaders else "not_owned"
    else:
        reason = save.get("reason") or "save collection block missing"
        for card in doc.get("cards", []):
            cid = card["id"]
            states[cid] = "owned" if cid in manual else "unknown"
            if cid in manual:
                reasons[cid] = "manual tick"
            else:
                reasons[cid] = reason
    counts = collections.Counter(states.values())
    return {
        "save": save.get("name", ""),
        "path": str(save.get("path", "")) if save.get("path") else "",
        "block_ok": bool(save.get("ok")),
        "reason": save.get("reason", ""),
        "counts": {key: counts.get(key, 0) for key in ("owned", "not_owned", "unknown")},
        "states": states,
        "reasons": reasons,
    }


def newest_save():
    if not SAVES.is_dir():
        return None
    saves = sorted(SAVES.glob("*.sav"), key=lambda path: path.stat().st_mtime)
    return saves[-1] if saves else None


def load_doc(path=OUT):
    if not Path(path).exists():
        raise SystemExit(f"{path} not found; run py tools/cards.py build")
    try:
        return load_json(path), None
    except DuplicateKey as exc:
        return None, str(exc)
    except (OSError, ValueError) as exc:
        return None, f"invalid JSON: {exc}"


def command_build(args):
    doc = build_doc()
    write_json(OUT, doc)
    counts = doc["counts"]
    print(f"wrote {OUT.relative_to(TRACKER)}")
    print(f"  {counts['total']} cards = {counts['main_collectible']} collectible main + "
          f"{counts['leaders']} leaders; {counts['excluded_summon_only']} summon-only excluded")
    print(f"  {counts['with_source']} with a source, {counts['unknown_source']} unknown; "
          f"packs {counts['packs']}")
    return 0


def command_check(args):
    errors, warnings = [], []
    doc, problem = (load_doc(args.file) if args.file else load_doc())
    if problem:
        print(f"error: {problem}")
        return 1
    if doc is None:
        print("error: gwent_cards.json not found")
        return 1
    validate_schema(doc, errors)
    live_checks(doc, errors, warnings)

    # The file is generated: a stale copy is a failure, but keep the message specific.
    try:
        expected = build_doc()
    except SystemExit as exc:
        expected = None
        errors.append(str(exc))
    if expected is not None and expected != doc:
        keys = ("counts", "excluded", "cards")
        changed = [key for key in keys if expected.get(key) != doc.get(key)]
        extra = sorted({card.get("id") for card in doc.get("cards", [])
                        if isinstance(card, dict)} - {
                            card.get("id") for card in expected.get("cards", [])})
        missing = sorted({card.get("id") for card in expected.get("cards", [])} - {
                            card.get("id") for card in doc.get("cards", [])
                            if isinstance(card, dict)})
        detail = ", ".join(changed) or "top-level fields"
        if extra:
            detail += f"; extra cards: {', '.join(extra[:5])}"
        if missing:
            detail += f"; missing cards: {', '.join(missing[:5])}"
        errors.append(f"gwent_cards.json is stale ({detail}); run py tools/cards.py build")

    save_path = Path(args.save) if args.save else newest_save()
    parsed = None
    if save_path is None or not save_path.exists():
        errors.append("no save found: the ownership parser must be exercised on at least one save")
    else:
        parsed = ownership(doc, save_path)
        if not parsed["block_ok"]:
            errors.append(f"save collection block is not readable: {parsed['reason']}")
        else:
            live = {(card.get("collection"), card.get("index")) for card in doc.get("cards", [])}
            save = probe.save_collection(save_path)
            for index, _copies in save["normal"]:
                if ("main", index) not in live:
                    errors.append(f"save collection has an unknown main card index {index}")
            for index, _copies in save["leaders"]:
                if ("leader", index) not in live:
                    errors.append(f"save collection has an unknown leader card index {index}")
            # A missing block must be unknown, never not owned.
            missing = ownership(doc, None)
            if any(state != "unknown" for state in missing["states"].values()):
                errors.append("a missing collection block produced a claim other than unknown")
            # A manual tick must not be overwritten by any save-derived state.
            candidate = next((card["id"] for card in doc.get("cards", [])
                              if parsed["states"].get(card["id"]) == "not_owned"), None)
            if candidate:
                ticked = ownership(doc, save_path, manual=[candidate])
                if ticked["states"].get(candidate) != "owned":
                    errors.append("a manual tick was overwritten")

    for warning in warnings:
        print("warning: " + warning)
    for error in errors:
        print("error: " + error)
    if errors:
        print(f"{len(errors)} problem(s); gwent_cards.json is not shippable")
        return 1
    counts = doc["counts"]
    windows = counts.get("windows") or {}
    line = (f"cards ok: {counts['total']} cards = {counts['main_collectible']} collectible main "
            f"+ {counts['leaders']} leaders; {counts['with_source']} sourced, "
            f"{counts['unknown_source']} unknown source, {counts.get('missable', 0)} missable "
            f"({windows.get('missable_tier_b', 0)} community, "
            f"{windows.get('missable_tier_a', 0)} gamefile), "
            f"{windows.get('one_time', 0)} one-time, {windows.get('none', 0)} no-window")
    if parsed is not None:
        owned = parsed["counts"]
        line += (f"; save {parsed['save'] or parsed['path']}: {owned['owned']} owned, "
                 f"{owned['not_owned']} not owned, {owned['unknown']} unknown")
    print(line)
    return 0


def command_ownership(args):
    doc, problem = load_doc(args.file)
    if problem:
        print(f"error: {problem}")
        return 1
    if doc is None:
        print("error: gwent_cards.json not found")
        return 1
    manual = []
    if args.manual:
        manual.extend(part for part in args.manual.split(",") if part.strip())
    if args.progress:
        progress = load_json(args.progress)
        manual.extend(progress.get("cards") or [])
    save_path = Path(args.save) if args.save else newest_save()
    if save_path is None:
        print("error: no save found; pass --save <file.sav>")
        return 1
    result = ownership(doc, save_path, manual=manual)
    if args.json:
        print(json.dumps(result, indent=2, sort_keys=True))
        return 0
    print(f"save: {result['save'] or result['path']}")
    if not result["block_ok"]:
        print(f"collection block: not readable ({result['reason']}); all states are unknown")
    print("  %d owned, %d not owned, %d unknown" % (
        result["counts"]["owned"], result["counts"]["not_owned"], result["counts"]["unknown"]))
    for cid in sorted(result["reasons"]):
        print(f"  unknown {cid}: {result['reasons'][cid]}")
    return 0


def main(argv=None):
    parser = argparse.ArgumentParser(description=__doc__)
    sub = parser.add_subparsers(dest="command", required=True)
    build = sub.add_parser("build", help="regenerate data/gwent_cards.json")
    build.set_defaults(func=command_build)
    check = sub.add_parser("check", help="validate the generated file against the game and a save")
    check.add_argument("--file", type=Path, default=None,
                       help="default: data/gwent_cards.json")
    check.add_argument("--save", type=Path, default=None,
                       help="default: newest save under W3_SAVES_DIR")
    check.set_defaults(func=command_check)
    own = sub.add_parser("ownership", help="print card ownership for one save")
    own.add_argument("--file", type=Path, default=OUT)
    own.add_argument("--save", type=Path, default=None)
    own.add_argument("--manual", help="comma-separated card ids that are ticked by hand")
    own.add_argument("--progress", type=Path, default=None,
                     help="progress.json; its cards array is used as manual ticks")
    own.add_argument("--json", action="store_true")
    own.set_defaults(func=command_ownership)
    args = parser.parse_args(argv)
    return args.func(args)


