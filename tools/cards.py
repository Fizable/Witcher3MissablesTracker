"""Generate and check `data/gwent_cards.json`: the Gwent collection ledger.

The card definitions are the game's own XML, not a wiki list. `tools/probe_cards.py` proved the
five resources, the string database and the save collection; this tool turns that probe into the
shipped index. It is generated data, never edited by hand:

  py cards.py build             write data/gwent_cards.json
  py cards.py check             validate the file against the game and one save
  py cards.py ownership         print owned / not owned / unknown for one save

What the index contains
-----------------------
* Every collectible main card and every leader definition. The denominator is **definitions**:
  202 collectible main cards plus 22 leaders. The 206-definition card table includes four
  summon-only tokens (`cow_czart`, `hemdal`, `berserker_bear`, `young_berserker_bear`); they are
  not collectible and are recorded in `excluded` with their parent and effect. 163 unique display
  names are not the denominator because the save's collection is keyed by card index, and several
  definitions intentionally share a display name.
* At least one source row per card: quest loot, quest reward, unique loot, vendor, a phase grant,
  a native script grant, the random merchant pool, a starter/deck default, or an opponent deck.
  Opponent deck membership is opponent evidence, not proof of a reward, and is marked `weak`.
  A card with no source is shipped as the explicit `unknown` source, not omitted.
* Evidence rows name the card XML, the source file and the string key/locId when one exists.
* Every card carries a `window`: a reviewed missable/one-time window or a documented no-window
  reason. The classifications are generated by `cardwindows.py` from the gamefile source rows and
  the reviewed decisions in `data/card_window_review.json`; Tier B rows name a source, URL and
  review date. A no-window row carries the concrete `sources_checked` and a reason that names one
  of them; the checker rejects a category-only reason.

Ownership
---------
`ownership` reads `CR4GwintManager.SBCollectionCard` / `SBLeaderCollectionCard` by `cardIndex`.
A missing or malformed collection block makes every card `unknown`; it never becomes `not owned`.
Manual ticks are accepted as an overlay and always win. No quest status is an input, so a tick
cannot be overwritten by one. `Crach_an_Craite` is a deck default rather than a collection row; it
is owned only when the collection has it or the save's Skellige deck-unlock fact is set, otherwise
`unknown` (never `not owned`).
"""
