"""The story path: the minimum main-story quests for the base game and each story DLC, in play order.

Reads data/route.json, data/outcomes.json and db/w3db.sqlite (read-only). Writes:

  data/story_path.json          the app reads this; one entry per pack, quests in order
  docs/STORY-PATH-REVIEW.md     the same list as checkboxes for the user to review

Quest set: every route node with kind "main". Its journal (files[0]) is looked up in
journal_quests, which gives the pack (files.pack: base, ep1 = Hearts of Stone, bob = Blood and Wine).

Order within a pack: the time each quest FIRST became active in the player's saves. That is the
minimum saves.mtime over the journal_transitions rows of its guid whose to_status is JS_Active or
JS_Success. A quest with no such row (not reached in the saves we have) keeps its route.json
position and goes straight after the nearest earlier route neighbour that has a time. The route
order alone is not the play order: the route lists quests by the game's CJournalQuest order.

Flags:
  optional   the route node has opt true, or the quest is one of several alternative ending
             journals of its pack (an outcome's terminal journal in outcomes.json). Alternatives
             carry alt_group "ending": only one of them plays in a given save.
  choice     the step is named by an outcome guidance row, or the route node has ending_relevant
             true (an ending choice; ordinary dialogue branches are not marked). The UI shows a neutral CHOICE tag; no ending is named.
  review     a required quest whose route node has no `when` and no `hard` prerequisite, and that no
             other main quest depends on (no quest_relations row of kind starts_or_advances,
             journal_test or fact_test from this quest to another main quest). These are the
             candidates the user should check by hand.

Run:  py tools/gamedb/export_story_path.py

Prints the counts per pack, the base-pack order with and without the save times, and how many
quests are marked review.
"""
import json
import sqlite3
import sys
from pathlib import Path

HERE = Path(__file__).resolve().parent
sys.path.insert(0, str(HERE))
import common  # noqa: E402  (DB path: W3_GAMEDB_OUT or <tracker>/db)
import paths  # noqa: E402

ROUTE = paths.TRACKER / "data" / "route.json"
OUTCOMES = paths.TRACKER / "data" / "outcomes.json"
OUT = paths.TRACKER / "data" / "story_path.json"
REVIEW = paths.TRACKER / "docs" / "STORY-PATH-REVIEW.md"
NOTE = "generated by tools/gamedb/export_story_path.py; reviewed by the user in docs/STORY-PATH-REVIEW.md"

# Pack order and labels the UI shows. A pack with no main route quest is not listed.
PACKS = [("base", "Main game"), ("ep1", "Hearts of Stone"), ("bob", "Blood and Wine")]
ALT_GROUP = "ending"
ALT_LABEL = "one of these, depending on your choices"
DEPENDENCY_KINDS = ("starts_or_advances", "journal_test", "fact_test")
PLAYED_STATUSES = ("JS_Active", "JS_Success")


def connect():
    uri = "file:" + common.DB.resolve().as_posix() + "?mode=ro"
    return sqlite3.connect(uri, uri=True)


def stem_of(journal_path):
    """'gameplay\\journal\\quests\\q505cirifree.journal' -> 'q505cirifree'."""
    name = journal_path.replace("\\", "/").rsplit("/", 1)[-1]
    return name.rsplit(".", 1)[0].lower()


def first_active_times(con):
    """quest guid -> the earliest save mtime at which one of the quest's OBJECTIVES is active or done.

    Read from every save's own journal (w3saves.sqlite). The quest's own entry is not used: several
    (Final Preparations, A Mysterious Passenger) sit "active" in the journal long before the player
    meets them, while an objective only turns active when the quest is really being played. A quest
    already under way in the oldest save has no transition, which is why the save journals are read
    rather than journal_transitions.
    """
    import common
    obj_quest = dict(con.execute("SELECT guid, quest_guid FROM journal_objectives WHERE quest_guid IS NOT NULL"))
    sv = sqlite3.connect(f"file:{common.SAVES_DB}?mode=ro", uri=True)
    mt = dict(sv.execute("SELECT save_id, mtime FROM saves"))
    out = {}
    for sid, g in sv.execute(
            f"SELECT save_id, guid FROM save_journal WHERE status IN ({','.join('?' * len(PLAYED_STATUSES))})",
            PLAYED_STATUSES):
        q = obj_quest.get(g)
        t = mt.get(sid)
        if q and t is not None and (q not in out or t < out[q]):
            out[q] = t
    return out


def play_order(route_ids, times):
    """Route order where a quest has a save time, sorted by that time; an untimed quest stays right
    after its nearest earlier route neighbour that has a time. Quests with no earlier timed
    neighbour go first, in route order. `route_ids` is the pack's route order; `times` maps id -> time
    or None."""
    timed = [q for q in route_ids if times.get(q) is not None]
    timed.sort(key=lambda q: times[q])  # sort is stable: equal times keep route order
    attached = {}  # timed id (or None for the front) -> untimed ids that follow it, in route order
    anchor = None
    for q in route_ids:
        if times.get(q) is not None:
            anchor = q
        else:
            attached.setdefault(anchor, []).append(q)
    out = list(attached.get(None, []))
    for q in timed:
        out.append(q)
        out.extend(attached.get(q, []))
    return out


def build():
    route = json.loads(ROUTE.read_text(encoding="utf-8"))
    outcomes = json.loads(OUTCOMES.read_text(encoding="utf-8"))
    main = [n for n in route["nodes"] if n.get("kind") == "main"]
    node_by_stem = {n["files"][0]: n for n in main}

    guidance_steps = {g.get("step") for o in outcomes.get("outcomes", {}).values() for g in o.get("guidance", [])}
    terminal_stems = {stem_of(o["journal_outcome"]["file"]) for o in outcomes.get("outcomes", {}).values()
                      if o.get("journal_outcome", {}).get("file")}

    with connect() as con:
        rows = con.execute(
            "SELECT jq.guid, jq.stem, f.pack FROM journal_quests jq LEFT JOIN files f ON f.file_id = jq.file_id"
        ).fetchall()
        guid_of = {}
        pack_of = {}
        for guid, stem, pack in rows:
            guid_of[stem] = guid
            pack_of[stem] = pack
        times_by_guid = first_active_times(con)
        rel_rows = con.execute(
            "SELECT a_guid, b_guid FROM quest_relations WHERE kind IN (%s)" % ",".join("?" * len(DEPENDENCY_KINDS)),
            DEPENDENCY_KINDS,
        ).fetchall()

    missing = [n["files"][0] for n in main if n["files"][0] not in guid_of]
    if missing:
        sys.exit(f"route main quests with no journal in the database: {missing}")
    main_guids = {guid_of[s] for s in node_by_stem}
    # a quest "depends" on another main quest through an edge from it to that quest
    outgoing = {}
    for a, b in rel_rows:
        if a in main_guids and b in main_guids and a != b:
            outgoing.setdefault(a, set()).add(b)

    packs = []
    report = {}
    for pack, label in PACKS:
        route_stems = [n["files"][0] for n in main if pack_of[n["files"][0]] == pack]
        if not route_stems:
            continue
        # alternatives: a pack with more than one main quest that is a terminal ending journal
        alt_here = {s for s in route_stems if s in terminal_stems}
        is_alt = alt_here if len(alt_here) > 1 else set()
        ids = {s: node_by_stem[s]["id"] for s in route_stems}
        times = {ids[s]: times_by_guid.get(guid_of[s]) for s in route_stems}
        ordered_ids = play_order([ids[s] for s in route_stems], times)
        stem_of_id = {v: k for k, v in ids.items()}
        quests = []
        for qid in ordered_ids:
            stem = stem_of_id[qid]
            n = node_by_stem[stem]
            alt = stem in is_alt
            optional = bool(n.get("opt")) or alt
            # Only choices that matter for an ending: `branch` is true for most main quests (any
            # dialogue that sets a fact), which would paint nearly every row as a choice.
            choice = n["id"] in guidance_steps or bool(n.get("ending_relevant"))
            review = False
            if not optional:
                no_gate = not n.get("when") and not n.get("hard")
                depended_on = bool(outgoing.get(guid_of[stem]))
                review = no_gate and not depended_on
            q = {"id": n["id"], "title": n["title"], "optional": optional}
            if alt:
                q["alt_group"] = ALT_GROUP
            q["choice"] = choice
            q["review"] = review
            quests.append(q)
        packs.append({"pack": pack, "label": label, "quests": quests})
        report[pack] = {"route_order": [ids[s] for s in route_stems], "play_order": ordered_ids,
                        "times": times, "stem_of_id": stem_of_id}
    return {"version": 1, "note": NOTE, "packs": packs}, report, node_by_stem


def write_review(doc, report, node_by_stem):
    lines = [
        "# Story path review",
        "",
        "Generated by `tools/gamedb/export_story_path.py`. Do not edit by hand; change the exporter or the",
        "data it reads, then run it again.",
        "",
        "The story path lists the quests that complete the main game and each story DLC, in the order your",
        "saves first reached them. Tick a box once you have checked that the quest is required to finish its",
        "part of the game. A quest that is not needed stays unticked; write the reason under its line.",
        "",
        "Each line shows the quest id. A quest marked **review** has no prerequisite in the route and no",
        "other main quest depends on it, so it may be a side step that was listed by mistake: check it.",
        "A quest marked **optional** is not needed to finish. A quest marked **one of these** is an",
        "alternative ending; only one of that group plays in a given save. A **CHOICE** quest is one where",
        "your decision changes the outcome. The order comes from the save times when the save reached the",
        "quest; a quest no save reached keeps its route position.",
        "",
    ]
    for pack in doc["packs"]:
        r = report[pack["pack"]]
        n_review = sum(1 for q in pack["quests"] if q["review"])
        lines += [f"## {pack['label']} ({len(pack['quests'])} quests, {n_review} to review)", ""]
        for q in pack["quests"]:
            tags = []
            if q["review"]:
                tags.append("**review**")
            if q["optional"]:
                tags.append("optional" if not q.get("alt_group") else "one of these")
            if q["choice"]:
                tags.append("CHOICE")
            seen = r["times"].get(q["id"]) is not None
            tags.append("in your save" if seen else "no save reached it yet")
            box = "[ ] required"
            lines.append(f"- {box}  `{q['id']}`  {q['title']}  ({'; '.join(tags)})")
        lines.append("")
    REVIEW.write_text("\n".join(lines), encoding="utf-8", newline="\n")


def main():
    doc, report, node_by_stem = build()
    OUT.write_text(json.dumps(doc, ensure_ascii=False, indent=1) + "\n", encoding="utf-8", newline="\n")
    write_review(doc, report, node_by_stem)

    for pack in doc["packs"]:
        qs = pack["quests"]
        req = [q for q in qs if not q["optional"]]
        print(f"{pack['pack']:5} {pack['label']:15} quests {len(qs):3}  required {len(req):3}  "
              f"optional {len(qs) - len(req):2}  choice {sum(q['choice'] for q in qs):3}  "
              f"review {sum(q['review'] for q in qs):3}  alt {sum(1 for q in qs if q.get('alt_group'))}")

    base = report["base"]
    names = {n["id"]: n["title"] for n in node_by_stem.values()}
    print()
    print("base pack: route.json order (left) and play order from the saves (right)")
    print("  'saved' = a save has this quest active or done; otherwise the quest kept its route place")
    left = [f"{i + 1:3} {names.get(q, q)} ({q})" for i, q in enumerate(base["route_order"])]
    right = [f"{i + 1:3} {names.get(q, q)}{'' if base['times'].get(q) is not None else ' [route]'}"
             for i, q in enumerate(base["play_order"])]
    width = max(len(x) for x in left) + 2
    for i in range(max(len(left), len(right))):
        a = left[i] if i < len(left) else ""
        b = right[i] if i < len(right) else ""
        print(f"{a:{width}}{b}")
    print()
    print(f"wrote {OUT}")
    print(f"wrote {REVIEW}")


if __name__ == "__main__":
    main()
