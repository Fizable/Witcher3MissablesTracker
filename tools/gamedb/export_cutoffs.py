"""Cutoffs the game database can name, in the item schema tools/derive.py resolves.

Reads db/w3db.sqlite (read-only) and data/cutoffs.json, and writes:

  data/cutoffs_generated.json   one item per quest A whose progress makes the game fail quests B;
                                derive.py appends these to the reviewed items
  docs/CUTOFF-REVIEW.md         the sign-off list: one section per A, a tick box per B

Selection, from quest_relations (kinds fails, fail_when_fact, fail_when_journal; A != B; both
journal entries in category 'quest'):

  fails, fail_when_journal   kept as the database has them
  fail_when_fact             kept only if some evidence row has hops <= 8 and is not truncated, and B
                             does not write the deciding fact itself (fact_ops set/add owned by B:
                             that is B's own bookkeeping, not a cutoff)
  reviewed                   a pair that a reviewed item in data/cutoffs.json already covers
                             (B in affects, A in closed_by) is dropped; the reviewed item wins

Run:  py tools/gamedb/export_cutoffs.py            write both files and print a summary
      py tools/gamedb/export_cutoffs.py --explain q402ciri
                                                   also print the decision for every pair with A = q402ciri
"""
import json
import sqlite3
import sys
from collections import Counter, defaultdict, deque
from pathlib import Path

HERE = Path(__file__).resolve().parent
sys.path.insert(0, str(HERE))
import common  # noqa: E402  (DB path: W3_GAMEDB_OUT or <tracker>/db)
import paths  # noqa: E402

DB = common.DB
GENERATED = paths.TRACKER / "data" / "cutoffs_generated.json"
REVIEW_MD = paths.TRACKER / "docs" / "CUTOFF-REVIEW.md"
CUTOFFS = paths.TRACKER / "data" / "cutoffs.json"

KINDS = ("fails", "fail_when_fact", "fail_when_journal")
MAX_HOPS = 8
BFS_BLOCKS = 40
MAX_FILES = 6
NOTE = ("generated by tools/gamedb/export_cutoffs.py from db/w3db.sqlite; do not hand-edit; "
        "reviewed corrections go in data/cutoffs.json")
CAVEAT = "Generated from the game files, not yet reviewed by a person."
JOURNAL_STATUS = {"JS_Active": "still open", "JS_Success": "completed", "JS_Failed": "failed",
                  "JS_Inactive": "not started yet"}


def connect():
    uri = "file:" + DB.resolve().as_posix() + "?mode=ro"
    return sqlite3.connect(uri, uri=True)


def listing(names):
    """'X', 'X and Y', 'X, Y and Z', or 'X, Y, Z and N more'."""
    if len(names) <= 3:
        return names[0] if len(names) == 1 else ", ".join(names[:-1]) + " and " + names[-1]
    return ", ".join(names[:3]) + f" and {len(names) - 3} more"


def gather(con):
    """Every kept (A, B) pair with its evidence rows, plus the decision for every pair seen."""
    stats = Counter()
    quest = {}  # journal guid -> {stem, tloc}, category 'quest' only
    for guid, stem, cat, tloc in con.execute("SELECT guid, stem, category, title_loc_id FROM journal_quests"):
        if cat == "quest":
            quest[guid] = {"stem": stem, "tloc": tloc}
    by_stem = {v["stem"]: v for v in quest.values()}
    if len(by_stem) != len(quest):
        raise SystemExit("duplicate quest stems in journal_quests (category 'quest')")

    text_cache = {}

    def text(loc):
        if loc is None:
            return None
        if loc not in text_cache:
            r = con.execute("SELECT text FROM strings WHERE loc_id=?", (loc,)).fetchone()
            text_cache[loc] = (r[0] or "").strip() if r else ""
        return text_cache[loc] or None

    def title(stem):
        q = by_stem.get(stem)
        return (text(q["tloc"]) if q else None) or stem

    writes_cache = {}

    def writes(guid):
        if guid not in writes_cache:
            writes_cache[guid] = {r[0] for r in con.execute(
                "SELECT DISTINCT fact FROM fact_ops WHERE op IN ('set','add') AND owner_quest=?", (guid,))}
        return writes_cache[guid]

    review = json.loads(CUTOFFS.read_text(encoding="utf-8"))
    covered = set()
    for it in review.get("items", []) + review.get("windows", []):
        for b in it["affects"]:
            for a in it["closed_by"]:
                covered.add((b.lower(), a.lower()))

    # pairs a person looked at and rejected: data/cutoffs.json "rejected_generated":
    # [{"closer": stem A, "affected": stem B, "why": "..."}]
    rejected = {(r["closer"].lower(), r["affected"].lower())
                for r in review.get("rejected_generated", [])}

    # (A stem, B stem) -> what the database says, per kind
    pairs = {}
    for a_g, b_g, kind, _n, ev in con.execute(
            f"SELECT a_guid, b_guid, kind, n, evidence FROM quest_relations WHERE kind IN ({','.join('?' * len(KINDS))})",
            KINDS):
        A, B = quest.get(a_g), quest.get(b_g)
        if A is None or B is None:
            stats["relation skipped: an end is not a category 'quest' journal entry"] += 1
            continue
        if A["stem"] == B["stem"]:
            stats["relation skipped: self"] += 1
            continue
        p = pairs.setdefault((A["stem"], B["stem"]), {"a_guid": a_g, "b_guid": b_g,
                                                       "ev": defaultdict(list)})
        p["ev"][kind].extend(json.loads(ev))
        stats[f"relation read: {kind}"] += 1

    kept, decisions = {}, []
    for (A, B), p in sorted(pairs.items()):
        rows, why_not = [], []
        for k in ("fails", "fail_when_journal"):
            rows += [dict(e, kind=k) for e in p["ev"][k]]
        fact_rows = p["ev"]["fail_when_fact"]
        if fact_rows:
            q = [e for e in fact_rows if (e.get("hops") or 99) <= MAX_HOPS and not e.get("truncated")]
            if not q:
                why_not.append("fail_when_fact: no evidence within 8 steps that is not truncated")
            else:
                own = sorted({e["fact"] for e in q if "fact" in e} & writes(p["b_guid"]))
                if own:
                    why_not.append(f"fail_when_fact: B writes its own deciding fact {', '.join(own)}")
                else:
                    rows += [dict(e, kind="fail_when_fact") for e in q]
        if not rows:
            verdict = "dropped: " + "; ".join(why_not)
            stats["pair dropped: " + why_not[0]] += 1
        elif (A.lower(), B.lower()) in rejected:
            verdict = "dropped: rejected in data/cutoffs.json rejected_generated"
            stats["pair dropped: rejected by review"] += 1
        elif (B, A) in covered:
            verdict = "dropped: covered by a reviewed item in data/cutoffs.json"
            stats["pair dropped: covered by reviewed item"] += 1
        else:
            verdict = "kept" + (f" (fails/journal part only; {'; '.join(why_not)})" if why_not else "")
            kept[(A, B)] = {"A": A, "B": B, "a_guid": p["a_guid"], "b_guid": p["b_guid"], "rows": rows}
        decisions.append({"A": A, "B": B, "kinds": sorted({r["kind"] for r in rows}) or
                          sorted(k for k in p["ev"] if p["ev"][k]), "verdict": verdict})

    stats["pairs kept"] = len(kept)
    return kept, decisions, stats, title, text, quest


def build_items(con, kept, title, text):
    """One item per A, in the schema tools/derive.py resolves."""
    by_a = defaultdict(list)
    for k in kept.values():
        by_a[k["A"]].append(k)

    file_paths = {}

    def path_of(fid):
        if fid not in file_paths:
            r = con.execute("SELECT path FROM files WHERE file_id=?", (fid,)).fetchone()
            file_paths[fid] = r[0] if r else f"file {fid}"
        return file_paths[fid]

    # setters: fact -> [(file_id, block, source)] for one owner guid
    setter_cache = {}

    def setters(fact, owner_guid):
        key = (fact, owner_guid)
        if key not in setter_cache:
            setter_cache[key] = con.execute(
                "SELECT file_id, owner_block, source FROM fact_ops WHERE fact=? AND op IN ('set','add') "
                "AND owner_quest=? ORDER BY (source='phase') DESC, file_id, owner_block",
                (fact, owner_guid)).fetchall()
        return setter_cache[key]

    activate = defaultdict(list)  # (file, block) -> objective guids the block activates
    for fid, blk, guid in con.execute(
            "SELECT file_id, block_idx, entry_guid FROM journal_ops "
            "WHERE op='activate' AND entry_class='CJournalQuestObjective' ORDER BY file_id, block_idx"):
        activate[(fid, blk)].append(guid)

    preds_cache = {}

    def preds(fid):
        if fid not in preds_cache:
            d = defaultdict(list)
            for src, dst in con.execute("SELECT src_block, dst_block FROM graph_edges WHERE file_id=?", (fid,)):
                d[dst].append(src)
            # Entering a sub-phase: its input block has no predecessor inside the sub-graph; control
            # comes from the phase block that embeds it, so continue from there.
            holder = {}
            for gi, par in con.execute("SELECT idx, parent_idx FROM graph_nodes WHERE file_id=? AND class='CQuestGraph'",
                                       (fid,)):
                holder[gi] = par
            for idx, gi in con.execute("SELECT idx, graph_idx FROM graph_nodes WHERE file_id=? "
                                       "AND class='CQuestPhaseInputBlock'", (fid,)):
                h = holder.get(gi)
                if h and not d.get(idx):
                    d[idx].append(h)
            preds_cache[fid] = d
        return preds_cache[fid]

    def objective_before(fid, block):
        """Nearest objective the file activates, walking backwards from a block (breadth first)."""
        seen, dq, visited = {block}, deque([block]), 0
        while dq and visited < BFS_BLOCKS:
            b = dq.popleft()
            visited += 1
            if activate.get((fid, b)):
                return activate[(fid, b)][0]
            for s in preds(fid).get(b, ()):
                if s not in seen:
                    seen.add(s)
                    dq.append(s)
        return None

    objective_text_cache = {}

    def objective_text(guid):
        if guid not in objective_text_cache:
            found = None
            for (loc,) in con.execute(
                    "SELECT title_loc_id FROM journal_entries WHERE guid=? AND class='CJournalQuestObjective' "
                    "AND title_loc_id IS NOT NULL", (guid,)):
                found = text(loc)
                if found:
                    break
            objective_text_cache[guid] = found
        return objective_text_cache[guid]

    items = []
    for A in sorted(by_a, key=lambda s: title(s).lower()):
        group = sorted(by_a[A], key=lambda k: k["B"])
        a_title = title(A)
        a_guid = group[0]["a_guid"]
        b_stems = [k["B"] for k in group]
        rows = [(k["B"], r) for k in group for r in k["rows"]]

        # closes_at_title: the objective whose activation sits just before the fact is set
        objective_counts = Counter()
        fact_pairs = Counter()
        for b, r in rows:
            if r["kind"] != "fail_when_fact":
                continue
            fact_pairs[(b, r["fact"])] += 1
            seen_here = set()
            for fid, blk, src in setters(r["fact"], a_guid):
                if (src == "phase" or str(src).startswith("script:")) and blk is not None:
                    g = objective_before(fid, blk)
                    t = objective_text(g) if g else None
                    if t:
                        seen_here.add(t)
            objective_counts.update(seen_here)
        if objective_counts:
            best = sorted(objective_counts.items(), key=lambda kv: (-kv[1], kv[0]))[0][0]
            closes_at_title = f'when {a_title} reaches "{best}"'
        else:
            closes_at_title = ""

        # why: the deciding fact (most B's) or journal status, with the file that sets it
        files_out = []
        why_parts = []
        fact_counts = Counter(f for (_b, f) in fact_pairs)
        if fact_counts:
            fact, _n = sorted(fact_counts.items(), key=lambda kv: (-kv[1], kv[0]))[0]
            set_files = [fid for fid, _blk, _src in setters(fact, a_guid)]
            set_path = path_of(set_files[0]) if set_files else None
            if set_path:
                why_parts.append(f"The game fails these quests once the fact {fact} is set during {a_title} "
                                 f"({set_path}).")
            else:
                why_parts.append(f"The game fails these quests once the fact {fact} is set during {a_title}.")
            files_out += [path_of(f) for f in dict.fromkeys(set_files)]
        journal = [r for _b, r in rows if r["kind"] == "fail_when_journal"]
        if journal:
            st = Counter(r.get("status") for r in journal).most_common(1)[0][0]
            where = path_of(journal[0]["file"])
            why_parts.append(f"The game fails these quests while the journal of {a_title} reads "
                             f"{JOURNAL_STATUS.get(st, st)} ({where}).")
            files_out += [where]
        direct = [r for _b, r in rows if r["kind"] == "fails"]
        if direct:
            where = path_of(direct[0]["file"])
            if not why_parts:
                why_parts.append(f"A journal block in {where} fails these quests directly.")
            files_out += [where]
        for _b, r in rows:
            if r["kind"] != "fails":
                files_out.append(path_of(r["file"]))
        files = list(dict.fromkeys(files_out))[:MAX_FILES]

        items.append({
            "id": "db_" + A,
            "event_name": a_title,
            "level": "stop",
            "mechanism": "journal_failure",
            "resource": "",
            "affects": b_stems,
            "closed_by": [A],
            "closes_at": "",
            "closes_at_title": closes_at_title,
            "action": f"Finish {listing([title(b) for b in b_stems])} before {a_title}",
            "headline": f"Finish these before {a_title} moves on",
            "why": " ".join(why_parts),
            "files": files,
            "evidence": "files",
            "caveats": [CAVEAT],
        })
    items.sort(key=lambda it: it["id"])
    return items


def review_markdown(con, items, kept, title, text):
    lines = [
        "# Cutoff review: quests the game fails",
        "",
        "Generated by `tools/gamedb/export_cutoffs.py` from `db/w3db.sqlite`. Nothing here has been "
        "reviewed by a person yet. `tools/derive.py` already loads every link in this list into "
        "`data/derived.json` as a stop warning, so the app shows them now. Ticking a box does not change "
        "the app, and there is no exclusion list yet: a link you reject needs an exclusion added to the "
        "exporter. Running the exporter again rewrites this file, so keep a copy of your ticks.",
        "",
        "What to do: for each quest listed below, read its evidence. Tick `- [x] keep` if the game really "
        "fails that quest once the closing quest reaches the point described. If it does not, leave the box "
        "empty and write one line under it saying why.",
        "",
        f"{len(items)} closing quests, {len(kept)} links to review.",
        "",
    ]
    for it in sorted(items, key=lambda i: title(i["closed_by"][0]).lower()):
        A = it["closed_by"][0]
        lines += [f"## {it['event_name']} (`{A}`)", "",
                  f"**Headline:** {it['headline']}", "",
                  f"**Closes at:** {it['closes_at_title'] or 'not found in the files; see the evidence below'}", "",
                  f"**Fails {len(it['affects'])} quest(s):** {it['action']}.", ""]
        for B in it["affects"]:
            lines += [f"### {title(B)} (`{B}`)", ""]
            seen = set()
            for k in kept.values():
                if k["A"] != A or k["B"] != B:
                    continue
                for r in k["rows"]:
                    if r["kind"] == "fail_when_fact":
                        key = ("fact", r["fact"], r["hops"], r["file"], r["fail_block"])
                        line = (f"fact `{r['fact']}` (hops {r['hops']}), file `{path_of_db(con, r['file'])}`, "
                                f"block {r['fail_block']}")
                        kind = "fail_when_fact"
                    elif r["kind"] == "fail_when_journal":
                        key = ("journal", r.get("status"), r["file"], r.get("fail_block"))
                        line = (f"journal status `{r.get('status')}` of the closing quest, file "
                                f"`{path_of_db(con, r['file'])}`, block {r.get('fail_block')}")
                        kind = "fail_when_journal"
                    else:
                        key = ("fails", r["file"], r["block"])
                        line = f"a journal block marks it failed, file `{path_of_db(con, r['file'])}`, block {r['block']}"
                        kind = "fails"
                    if key in seen:
                        continue
                    seen.add(key)
                    lines.append(f"- {kind}: {line}")
            lines += ["", "- [ ] keep", ""]
    return "\n".join(lines) + "\n"


_path_cache = {}


def path_of_db(con, fid):
    if fid not in _path_cache:
        r = con.execute("SELECT path FROM files WHERE file_id=?", (fid,)).fetchone()
        _path_cache[fid] = r[0] if r else f"file {fid}"
    return _path_cache[fid]


def main(argv):
    explain = argv[argv.index("--explain") + 1] if "--explain" in argv else None
    con = connect()
    kept, decisions, stats, title, text, _quest = gather(con)
    items = build_items(con, kept, title, text)

    GENERATED.write_text(json.dumps({"version": 1, "note": NOTE, "items": items}, indent=2,
                                    ensure_ascii=False) + "\n", encoding="utf-8")
    REVIEW_MD.write_text(review_markdown(con, items, kept, title, text), encoding="utf-8")

    print("selection:")
    for k in sorted(stats):
        print(f"  {k}: {stats[k]}")
    print(f"items: {len(items)}")
    print(f"affected pairs: {sum(len(it['affects']) for it in items)}")
    print(f"wrote {GENERATED.relative_to(paths.TRACKER).as_posix()}")
    print(f"wrote {REVIEW_MD.relative_to(paths.TRACKER).as_posix()}")
    if explain:
        print(f"\ndecisions for A = {explain}:")
        for d in decisions:
            if d["A"] == explain:
                print(f"  {title(d['B'])} ({d['B']}) [{', '.join(d['kinds'])}]: {d['verdict']}")


if __name__ == "__main__":
    main(sys.argv[1:])
